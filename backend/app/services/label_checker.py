def check_image_label_from_url(image_url, timeout=15):
    """
    Fetch image -> OCR -> detect keyword -> compute matched keyword word boxes area ratio.

    Returns:
    {
      image_url,
      fetched,
      size_bytes,
      width,height,
      ocr_text,
      matched_words: [{word, box:[x,y,w,h]}],
      matched_area_ratio,
      compliant,
      notes:[...]
    }
    """
    result = {
        "image_url": image_url,
        "fetched": False,
        "size_bytes": None,
        "width": None,
        "height": None,
        "ocr_text": None,
        "matched_words": [],
        "matched_area_ratio": 0.0,
        "compliant": False,
        "notes": [],
    }

    # 1) Fetch image
    headers = {"User-Agent": "Mozilla/5.0"}
    resp = requests.get(image_url, timeout=timeout, headers=headers)
    resp.raise_for_status()

    content = resp.content
    result["fetched"] = True
    result["size_bytes"] = len(content)

    # 2) Decode with PIL
    img = Image.open(io.BytesIO(content)).convert("RGB")
    w, h = img.size
    result["width"] = w
    result["height"] = h

    if not w or not h:
        result["notes"].append("invalid_image_dimensions")
        return result

    image_area = float(w * h)

    # 3) OCR with word boxes
    try:
        arr = np.array(img)

        # grayscale for OCR
        gray = (0.299 * arr[:, :, 0] + 0.587 * arr[:, :, 1] + 0.114 * arr[:, :, 2]).astype(np.uint8)

        data = pytesseract.image_to_data(gray, output_type=pytesseract.Output.DICT)

        words = data.get("text", []) or []
        full_text = " ".join([t for t in words if t and t.strip()])
        result["ocr_text"] = full_text.strip()

        # Fast fail: keyword phrase not present at all
        if not contains_ai_keyword(full_text):
            result["compliant"] = False
            result["notes"].append("no_ai_keywords_in_ocr_text")
            return result

        # 4) Sum ONLY matched keyword word boxes
        matched_area = 0.0
        matched_words = []

        n = len(words)
        for i in range(n):
            word_raw = (words[i] or "").strip()
            if not word_raw:
                continue

            tok = normalize_word_token(word_raw)
            if not tok:
                continue

            if tok in KEYWORD_TOKENS:
                left = int(data["left"][i])
                top = int(data["top"][i])
                bw = int(data["width"][i])
                bh = int(data["height"][i])

                box_area = float(max(bw, 0) * max(bh, 0))
                matched_area += box_area
                matched_words.append({"word": word_raw, "box": [left, top, bw, bh]})

        ratio = matched_area / image_area if image_area > 0 else 0.0

        result["matched_words"] = matched_words
        result["matched_area_ratio"] = ratio

        # ✅ Rule 3(3) MVP: label >=10% surface area
        result["compliant"] = ratio >= 0.10

        if result["compliant"]:
            result["notes"].append("label_area_meets_10_percent")
        else:
            result["notes"].append("label_detected_but_area_below_10_percent")

        if not matched_words:
            result["notes"].append("keyword_phrase_found_but_token_boxes_not_matched")

        return result

    except Exception as e:
        result["notes"].append(f"ocr_error: {e}")
        result["compliant"] = False
        return result


