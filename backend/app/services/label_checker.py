# ----------------------------
# Keywords
# ----------------------------

AI_KEYWORDS = [
    "ai-generated",
    "ai generated",
    "synthetic",
    "artificial",
    "deepfake",
    "computer generated",
    "generated by ai",
    "ai content",
]


def _build_keyword_tokens():
    tokens = set()
    for kw in AI_KEYWORDS:
        for tok in kw.replace("-", " ").split():
            tok = tok.strip().lower()
            if tok:
                tokens.add(tok)

    # extra variants often seen from OCR
    tokens.update(["aigenerated", "computergenerated"])
    return tokens


KEYWORD_TOKENS = _build_keyword_tokens()


# ----------------------------
# Helpers
# ----------------------------

def normalize_text(s: str) -> str:
    return (s or "").lower().replace("\n", " ").strip()


def contains_ai_keyword(text: str) -> bool:
    t = normalize_text(text)
    return any(kw in t for kw in AI_KEYWORDS)


def normalize_word_token(word: str) -> str:
    """
    Normalize OCR word for matching:
    - lower
    - remove non-alphanumeric characters
    """
    w = (word or "").strip().lower()
    w = re.sub(r"[^a-z0-9]+", "", w)
    return w


