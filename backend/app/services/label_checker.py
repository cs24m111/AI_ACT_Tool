def check_labels(scraped_data, url=None):
    """
    Check both:
    (A) Textual labels found in HTML (scraped_data["labels"])
    (B) Visible label on the FIRST image (scraped_data["images"][0])

    Returns:
    {
      desc_compliant, img_compliant,
      desc_labels, image_label_result,
      issues, score
    }
    """
    result = {
        "desc_compliant": False,
        "img_compliant": False,
        "desc_labels": [],
        "image_label_result": None,
        "issues": [],
        "score": 0,
        "source_url": url,
    }

    # --- (A) Description / HTML labels ---
    text_blob = ""
    for lbl in scraped_data.get("labels", []) or []:
        text_blob += (lbl.get("text") or "") + " "

    desc_text = normalize_text(text_blob)
    found_desc = [kw for kw in AI_KEYWORDS if kw in desc_text]

    if found_desc:
        result["desc_compliant"] = True
        result["desc_labels"] = found_desc

    # --- (B) Image label check (first image only) ---
    images = scraped_data.get("images", []) or []
    first_image = images[0] if images else None

    if first_image:
        try:
            img_check = check_image_label_from_url(first_image)
            result["image_label_result"] = img_check
            result["img_compliant"] = bool(img_check.get("compliant", False))
        except Exception as e:
            result["issues"].append("image_check_error: " + str(e))
    else:
        result["issues"].append("no_image_found")

    # --- Score (simple) ---
    score = 0
    score += 50 if result["desc_compliant"] else 0
    score += 50 if result["img_compliant"] else 0
    result["score"] = score

    if not result["desc_compliant"] and not result["img_compliant"]:
        result["issues"].append("no_ai_label_detected_in_desc_or_image")

    return result


